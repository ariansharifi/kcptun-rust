//! Go's `syscall.Errno` error text, ported from Go's own tables (**DECISIONS D30**).
//!
//! Go does not call `strerror(3)`. Every `syscall.Errno` renders itself from a table the Go
//! distribution generates per `GOOS`/`GOARCH` — `syscall/zerrors_linux_amd64.go` line 1453 is
//! `98: "address already in use"` — and falls back to `"errno " + itoa(n)` for anything that
//! table has no text for (`syscall/syscall_unix.go`, `func (e Errno) Error()`).
//!
//! Taking the C library's message instead only ever *looked* right, because glibc happens to
//! agree with Go for the common errnos. Step 10.5 found where it does not: a **static musl**
//! build's `strerror` spells `EADDRINUSE` `Address in use` where glibc's spells it
//! `Address already in use`; Go's table entry is the lower-case `address already in use`. So
//! `kcptun-server -l :29900` on a port already taken printed `bind: address in use` on musl
//! where Go prints `bind: address already in use`. musl is the container image's libc and a
//! shipped artifact (D07), so
//! that was the binary most users would actually run. The port's log lines are a byte-for-byte
//! contract (`docs/porting-guide.md` §4, and the CLI differential of step 09.5), and a contract
//! that is target-dependent is no contract — so the table is ported, which is also simply what
//! Go does.
//!
//! [`go_error_text`] is the single renderer: `kcptun_std::config::go_error_text` (and through it
//! Go's `*net.OpError` builders in `kcptun_std::mainutil`) and `kcptun_tcpraw::addr::errno_text`
//! are thin wrappers over it. It lives in this crate rather than in `kcptun-std` — where D30
//! puts it — only because `kcptun-std` *depends on* `kcptun-tcpraw`, which needs the same
//! renderer; `kcptun-kcp` is the crate both can reach, and it already hosts the ports of Go's
//! `net` (`addr`) and `sort` (`gosort`). `kcptun_std::goerrno` re-exports this module, so D30's
//! name still resolves.
//!
//! **Platform coverage.** The tables carried are the ones of DECISIONS D22: Linux on
//! `x86_64`/`x86`/`aarch64`/`arm`, macOS on `x86_64`/`aarch64`, and FreeBSD on `x86_64`. Any
//! other target keeps the previous behaviour — the C library's message, lower-cased — because
//! shipping an unverified table would be worse than the libc text it replaces: Linux `mips`, for
//! one, numbers its errnos differently (`EADDRINUSE` is 125 there), so the generic table would
//! name the wrong error rather than merely word it differently. [`has_table`] reports which
//! applies.
//!
//! The table itself is in [`table`], generated by `tools/gen-errno-table.py` from
//! `testdata/vectors/errno.json` (`tools/govectors` area `errno`, which reads Go's own
//! `zerrors_*.go`) and checked against that vector file — for *every* platform, not only the
//! host's — by `tests::vectors_errno_tables`.
