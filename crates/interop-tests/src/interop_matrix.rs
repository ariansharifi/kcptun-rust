//! The Go↔Rust interop matrix (plan step 09.4): every case runs the real `kcptun-client` and
//! `kcptun-server` binaries on loopback in all four pairings.
//!
//! ```text
//!   go → rs     Go client   ══KCP/UDP══▶  Rust server      the port's receive path
//!   rs → go     Rust client ══KCP/UDP══▶  Go server        the port's send path
//!   go → go     Go client   ══KCP/UDP══▶  Go server        control: the harness itself
//!   rs → rs     Rust client ══KCP/UDP══▶  Rust server      control: the port is self-consistent
//! ```
//!
//! **A failing control means the harness is wrong, not the port.** `go → go` runs nothing of
//! ours at all, so a red cell there is a bug in this file (or in the workload, the target server
//! or the machine); it is never a reason to change `crates/client`, `crates/server` or anything
//! below them to match. `rs → rs` failing while both crossings pass would likewise point at the
//! harness, since the crossings exercise strictly more of the port.
//!
//! # The cases
//!
//! | Group | Cases | What it covers |
//! |---|---|---|
//! | `crypt/*` | 15 | every `-crypt` method at kcptun's defaults |
//! | `pair/NN` | [`pairwise_cases`] | all 2-way combinations of compression, smux version, FEC, QPP, mode, `-conn` and MTU |
//! | `production` | 1 | the fixed profile from the plan (`-mode normal -crypt xor -mtu 1390 …`) |
//!
//! The pairwise group is generated by [`matrix::pairwise_indices`](crate::matrix::pairwise_indices)
//! over [`DIMENSIONS`], so it is deterministic: the same list, in the same order, on every run and
//! on every machine. [`case_table`] prints it as the Markdown that `docs/interop-matrix.md` is
//! regenerated from.
//!
//! `-crypt` is deliberately *not* one of the pairwise dimensions: the plan gives it its own 15
//! default-configuration cases ("All 15 crypt modes run with the defaults. The other dimensions
//! are covered pairwise"), and folding 15 levels into the expansion would force at least 60 rows
//! for no extra two-way coverage.
//!
//! # The workload
//!
//! Each run drives one [`MatrixTarget`] through the tunnel, three times:
//!
//! 1. **bulk**: one stream, [`Workload::bulk_bytes`] each way, SHA-256 verified in both
//!    directions;
//! 2. **streams**: [`Workload::streams`] concurrent streams, each a
//!    [`Workload::stream_bytes`] request/echo pair, SHA-256 verified;
//! 3. **half-close**: one stream whose answer is produced only *after* the application's
//!    `shutdown(SHUT_WR)`, so every response byte crosses a half-closed stream.
//!
//! (1) and (2) read their whole answer *before* half-closing, so they never depend on half-close
//! semantics; (3) depends on nothing else. Both processes' logs are then scanned for the
//! [`ERROR_MARKERS`] denylist: the substrings neither implementation prints in a healthy run,
//! rather than against an allowlist of known-good lines.
//!
//! # The expected Go behaviours
//!
//! Exactly one thing is allowed to differ, and only in workload (3), and only with a **Go
//! client**. Both halves of it reproduce in the `go -> go` control, which runs no Rust at all.
//!
//! * **V11**: Go's smux discards received-but-unread data when the peer's FIN completes a
//!   half-close (`tryHalfCloseCleanup` -> `streamClosed` -> `recycleTokens`), so a Go client cuts
//!   the answer at whatever was still unread in smux's buffer when the FIN landed, usually, but
//!   not always, a frame boundary. Measured here on the real binaries: 57344 of 65536 bytes
//!   (`go -> rs`) and 49152 of 65536 (`go -> go`).
//! * **V04**, with `-QPP` on top, Go's `QPPPort` implements no `CloseWrite`, so kcptun's `Pipe`
//!   falls back to a full `Close` (`std/copy.go:72`) and tears the stream down the instant the
//!   application half-closes; nothing of the answer survives.
//!
//! [`Expectation`] encodes both. Whatever does arrive must still be a correct *prefix* of the
//! expected stream, and the `pipe:` line the Go peer logs about its own torn-down stream is
//! allowed (and recorded as a note). A **Rust client is held to a complete response against
//! either server**: that is what V11 and V04 bought, and the `rs -> rs` control stays strict.
//!
//! # Running it
//!
//! ```sh
//! cargo build --release -p kcptun-client -p kcptun-server
//! tools/fetch-reference.sh --skip-latest --skip-tests     # Go reference binaries
//! cargo test -p kcptun-interop-tests --test interop_matrix -- --ignored --nocapture interop_matrix_full
//! ```
//!
//! (the trailing test name matters: without it libtest also runs `interop_matrix_smoke`, in
//! parallel with the full matrix, and the two runs would measure each other)
//!
//! `KCPTUN_INTEROP_MATRIX_FILTER=pair/07` runs one case (substring match on the case id), and
//! `KCPTUN_INTEROP_MATRIX_OUT=docs/interop-matrix.md` writes the report instead of only printing
//! it. Every process is a `Proc` and dies with its [`Tunnel`], on the panic and timeout paths too.

