/// The pairwise expansion of [`DIMENSIONS`]: every pair of values of any two dimensions appears
/// in at least one case. Deterministic: the same list in the same order on every run.
pub fn pairwise_cases() -> Vec<InteropCase> {
    let levels: Vec<usize> = DIMENSIONS.iter().map(|d| d.levels.len()).collect();
    pairwise_indices(&levels)
        .into_iter()
        .enumerate()
        .map(|(n, row)| {
            let mut pair = Pair::defaults();
            let mut parts: Vec<String> = Vec::with_capacity(DIMENSIONS.len());
            for (dim, &i) in DIMENSIONS.iter().zip(&row) {
                let level = dim.levels[i];
                (level.apply)(&mut pair);
                parts.push(format!("{}={}", dim.name, level.name));
            }
            InteropCase {
                id: format!("pair/{:02}", n + 1),
                group: Group::Pairwise,
                summary: parts.join(" "),
                client: pair.client,
                server: pair.server,
                key: pair.key,
            }
        })
        .collect()
}

