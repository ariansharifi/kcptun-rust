/// How much traffic one run pushes through the tunnel.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Workload {
    /// Bytes sent **and** echoed back on the single bulk stream.
    pub bulk_bytes: u64,
    /// How many concurrent short streams to open.
    pub streams: usize,
    /// Bytes sent and echoed back on each of those streams.
    pub stream_bytes: u64,
    /// Bytes the half-close probe asks for after it has shut its write side.
    pub response_bytes: u64,
    /// Bytes the half-close probe sends before shutting its write side.
    pub request_bytes: u64,
    /// How long the half-close probe waits after `shutdown(SHUT_WR)` before it starts reading.
    ///
    /// The delay is what makes the probe *decisive* rather than a race: while it runs, the whole
    /// answer and the peer's FIN pile up in the stream's receive buffer, which is exactly the
    /// state in which Go's `recycleTokens` throws them away (V11). A Rust client must still hand
    /// over every byte, so the strict side of the matrix gets harder, not easier, and a Go
    /// client's truncation stops depending on how fast the machine happens to be.
    pub half_close_read_delay: Duration,
}

/// The plan's workload: 20 MB bulk each way plus 100 concurrent small streams, and the
/// half-close probe on top.
pub const FULL: Workload = Workload {
    bulk_bytes: 20 * 1000 * 1000,
    streams: 100,
    stream_bytes: 16 * 1024,
    response_bytes: 256 * 1024,
    request_bytes: 4 * 1024,
    half_close_read_delay: Duration::from_millis(250),
};

/// A smaller workload for a quick check of the harness itself.
pub const SMOKE: Workload = Workload {
    bulk_bytes: 1 << 20,
    streams: 8,
    stream_bytes: 4 * 1024,
    response_bytes: 64 * 1024,
    request_bytes: 1024,
    half_close_read_delay: Duration::from_millis(250),
};

/// Writes a [`MatrixTarget`] header.
async fn send_header<W: tokio::io::AsyncWrite + Unpin>(
    w: &mut W,
    mode: TargetMode,
) -> io::Result<()> {
    w.write_all(&mode.header()).await
}

/// One echo exchange: header, `len` bytes out and `len` bytes back, SHA-256 verified, then a
/// half-close and the end of the stream.
///
/// The answer is read in full *before* the half-close, so this workload does not depend on
/// half-close semantics at all: that is what the third workload is for.
async fn echo_exchange(stream: &mut LocalStream, seed: u64, len: u64) -> Result<(), String> {
    let (send, sha) = {
        let (mut r, mut w) = tokio::io::split(&mut *stream);
        let send = async {
            send_header(&mut w, TargetMode::Echo).await?;
            write_prng_stream(&mut w, seed, len).await
        };
        // Both halves run in this task; `tokio::spawn` would need a `'static` stream.
        tokio::join!(send, hash_exact(&mut r, len))
    };
    match (sha, send) {
        (Ok(sha), Ok(())) => {
            if sha != PrngStream::sha256_hex(seed, len) {
                return Err(format!(
                    "echo of {len} bytes (seed {seed}) came back with SHA-256 {sha}, expected {}",
                    PrngStream::sha256_hex(seed, len)
                ));
            }
        }
        (Ok(_), Err(e)) => return Err(format!("sending {len} bytes: {e}")),
        (Err(e), Ok(())) => return Err(format!("reading the echo of {len} bytes: {e}")),
        (Err(e), Err(w)) => {
            return Err(format!(
                "reading the echo of {len} bytes: {e} (request: {w})"
            ));
        }
    }
    stream
        .shutdown()
        .await
        .map_err(|e| format!("half-closing after the echo: {e}"))?;
    end_of_stream(stream).await
}

/// Fails unless the stream ends now.
///
/// A reset counts: the application has already read every byte it asked for, both kcptun peers
/// are tearing the stream down, and whether the last `close(2)` lands as a FIN or an RST on
/// loopback is a race with no bearing on data integrity. Anything else (a stray byte) is a
/// failure.
async fn end_of_stream(stream: &mut LocalStream) -> Result<(), String> {
    let mut buf = [0u8; 64];
    match stream.read(&mut buf).await {
        Ok(0) => Ok(()),
        Ok(n) => Err(format!(
            "{n} unexpected bytes after the end of the stream: {:?}",
            &buf[..n.min(16)]
        )),
        Err(e) if e.kind() == io::ErrorKind::ConnectionReset => Ok(()),
        Err(e) => Err(format!("waiting for the end of the stream: {e}")),
    }
}

/// The half-close probe: send a request, `shutdown(SHUT_WR)`, then read the answer the target
/// only starts producing once it has seen that EOF.
///
/// Returns how many response bytes arrived. Every byte that arrives is checked against the
/// expected stream as it arrives, so a truncation allowed by [`Expectation`] still cannot hide
/// corruption: a wrong byte fails the run whatever the expectation says.
async fn half_close_probe(
    stream: &mut LocalStream,
    seed: u64,
    len: u64,
    request_bytes: u64,
    read_delay: Duration,
    expected: &[u8],
) -> Result<u64, String> {
    send_header(stream, TargetMode::Respond { seed, len })
        .await
        .map_err(|e| format!("half-close probe: sending the header: {e}"))?;
    write_prng_stream(stream, seed ^ 0x5a5a, request_bytes)
        .await
        .map_err(|e| format!("half-close probe: sending the request: {e}"))?;
    stream
        .shutdown()
        .await
        .map_err(|e| format!("half-close probe: shutdown(SHUT_WR): {e}"))?;
    // Let the answer and the peer's FIN arrive before reading a byte of either; see
    // `Workload::half_close_read_delay`.
    tokio::time::sleep(read_delay).await;

    let mut got: Vec<u8> = Vec::with_capacity(expected.len());
    let mut buf = vec![0u8; BUF_SIZE];
    loop {
        let n = match stream.read(&mut buf).await {
            Ok(0) => break,
            Ok(n) => n,
            // The peer resetting after a V04 teardown is the truncation itself, not a new fault;
            // the caller decides whether the resulting length is acceptable.
            Err(e) if e.kind() == io::ErrorKind::ConnectionReset => break,
            Err(e) => return Err(format!("half-close probe: reading the response: {e}")),
        };
        if got.len() + n > expected.len() {
            return Err(format!(
                "half-close probe: the response is longer than the {} bytes asked for",
                expected.len()
            ));
        }
        if buf[..n] != expected[got.len()..got.len() + n] {
            let at = got.len()
                + buf[..n]
                    .iter()
                    .zip(&expected[got.len()..])
                    .position(|(a, b)| a != b)
                    .unwrap_or(0);
            return Err(format!(
                "half-close probe: the response differs from the expected stream at byte {at}"
            ));
        }
        got.extend_from_slice(&buf[..n]);
    }
    Ok(got.len() as u64)
}

