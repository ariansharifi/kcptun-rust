/// Size of a [`MatrixTarget`] request header.
const HEADER_LEN: usize = 24;
/// Magic at the front of a [`MatrixTarget`] request header.
const MAGIC: [u8; 4] = *b"KMX1";
/// Header mode: echo everything that follows.
const MODE_ECHO: u8 = 1;
/// Header mode: read to EOF, then answer.
const MODE_RESPOND: u8 = 2;

/// What the application asks a [`MatrixTarget`] connection to do.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum TargetMode {
    /// Echo every byte after the header back.
    Echo,
    /// Read the rest of the request to EOF, then send `len` bytes of `PrngStream(seed)`.
    Respond { seed: u64, len: u64 },
}

impl TargetMode {
    /// The 24-byte header that selects this mode.
    fn header(self) -> [u8; HEADER_LEN] {
        let mut h = [0u8; HEADER_LEN];
        h[..4].copy_from_slice(&MAGIC);
        match self {
            TargetMode::Echo => h[4] = MODE_ECHO,
            TargetMode::Respond { seed, len } => {
                h[4] = MODE_RESPOND;
                h[8..16].copy_from_slice(&seed.to_le_bytes());
                h[16..24].copy_from_slice(&len.to_le_bytes());
            }
        }
        h
    }

    /// Parses a header, or `None` if it is not one of ours.
    fn parse(h: &[u8; HEADER_LEN]) -> Option<Self> {
        if h[..4] != MAGIC {
            return None;
        }
        let seed = u64::from_le_bytes(h[8..16].try_into().ok()?);
        let len = u64::from_le_bytes(h[16..24].try_into().ok()?);
        match h[4] {
            MODE_ECHO => Some(TargetMode::Echo),
            MODE_RESPOND => Some(TargetMode::Respond { seed, len }),
            _ => None,
        }
    }
}

/// The matrix's one target server: it serves all three workloads, so a case needs a single `-t`.
///
/// Every connection starts with a [`HEADER_LEN`]-byte header naming the mode. `Echo` is the
/// ordinary echo target the bulk and concurrent-stream workloads use; `Respond` reads the request
/// to EOF and only *then* answers, which is what puts every response byte on a half-closed
/// stream.
#[derive(Debug)]
pub struct MatrixTarget {
    addr: SocketAddr,
    connections: Arc<AtomicU64>,
    bad_headers: Arc<AtomicU64>,
    acceptor: Acceptor,
}

impl MatrixTarget {
    /// Starts the target on `127.0.0.1` with an ephemeral port.
    pub async fn start() -> io::Result<Self> {
        let (listener, addr) = bind_tcp().await?;
        let connections = Arc::new(AtomicU64::new(0));
        let bad_headers = Arc::new(AtomicU64::new(0));
        let conns = Arc::clone(&connections);
        let bad = Arc::clone(&bad_headers);
        let acceptor = serve(listener, move |mut conn| {
            conns.fetch_add(1, Ordering::SeqCst);
            let bad = Arc::clone(&bad);
            async move {
                let mut header = [0u8; HEADER_LEN];
                if conn.read_exact(&mut header).await.is_err() {
                    bad.fetch_add(1, Ordering::SeqCst);
                    return;
                }
                let Some(mode) = TargetMode::parse(&header) else {
                    bad.fetch_add(1, Ordering::SeqCst);
                    return;
                };
                match mode {
                    TargetMode::Echo => {
                        let mut buf = vec![0u8; BUF_SIZE];
                        loop {
                            match conn.read(&mut buf).await {
                                Ok(0) => break,
                                Ok(n) => {
                                    if conn.write_all(&buf[..n]).await.is_err() {
                                        return;
                                    }
                                }
                                Err(_) => return,
                            }
                        }
                        let _ = conn.shutdown().await;
                    }
                    TargetMode::Respond { seed, len } => {
                        let mut sink = vec![0u8; BUF_SIZE];
                        loop {
                            match conn.read(&mut sink).await {
                                Ok(0) => break,
                                Ok(_) => {}
                                Err(_) => return,
                            }
                        }
                        if write_prng_stream(&mut conn, seed, len).await.is_ok() {
                            let _ = conn.shutdown().await;
                        }
                    }
                }
                // Drain until the peer closes, so a complete answer is never turned into a reset.
                let mut sink = [0u8; 1024];
                while matches!(conn.read(&mut sink).await, Ok(n) if n > 0) {}
            }
        });
        Ok(MatrixTarget {
            addr,
            connections,
            bad_headers,
            acceptor,
        })
    }

    /// The `-t` value for this target.
    pub fn target(&self) -> String {
        self.addr.to_string()
    }

    /// Connections accepted so far.
    pub fn connections(&self) -> u64 {
        self.connections.load(Ordering::SeqCst)
    }

    /// Connections that did not start with a readable header: a tunnel that corrupts or
    /// reorders the first bytes shows up here rather than as a silent hang.
    pub fn bad_headers(&self) -> u64 {
        self.bad_headers.load(Ordering::SeqCst)
    }

    /// Stops accepting and shuts every open connection down.
    pub async fn shutdown(mut self) {
        self.acceptor.shutdown().await;
    }
}

