/// Which part of the matrix a case belongs to.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Group {
    /// One case per `-crypt` method, everything else at kcptun's defaults.
    Crypt,
    /// The pairwise expansion of [`DIMENSIONS`].
    Pairwise,
    /// The plan's fixed production profile.
    Production,
}

impl Group {
    /// `crypt`, `pairwise` or `production`.
    pub fn name(self) -> &'static str {
        match self {
            Group::Crypt => "crypt",
            Group::Pairwise => "pairwise",
            Group::Production => "production",
        }
    }
}

impl fmt::Display for Group {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.name())
    }
}

/// One matrix case: the two command lines (they differ for the FEC-mismatch case) and the key.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct InteropCase {
    /// Stable identifier, e.g. `crypt/salsa20`, `pair/07`, `production`.
    pub id: String,
    /// Which part of the matrix this case belongs to.
    pub group: Group,
    /// `dimension=value` list for the pairwise group, or a short description otherwise.
    pub summary: String,
    /// The client's configuration.
    pub client: Case,
    /// The server's configuration.
    pub server: Case,
    /// The `-key` both sides are given.
    pub key: String,
}

impl InteropCase {
    /// True when `-QPP` is on (both sides always agree about that).
    pub fn qpp(&self) -> bool {
        self.client.qpp
    }

    /// The exact configuration, as several lines: what a failing case prints so it can be
    /// reproduced by hand.
    pub fn describe(&self) -> String {
        format!(
            "case {id} (group {group})\n  {summary}\n  key: {key} ({keylen} bytes)\n  \
             client: {client}\n  server: {server}\n  client flags: {cargs}\n  server flags: {sargs}",
            id = self.id,
            group = self.group,
            summary = self.summary,
            key = if self.key.len() > 40 {
                format!("{}…", &self.key[..40])
            } else {
                self.key.clone()
            },
            keylen = self.key.len(),
            client = self.client.label(),
            server = self.server.label(),
            cargs = self.client.args(Side::Client).join(" "),
            sargs = self.server.args(Side::Server).join(" "),
        )
    }
}

/// A client/server configuration pair under construction; what a [`Level`] mutates.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Pair {
    /// The client's configuration.
    pub client: Case,
    /// The server's configuration.
    pub server: Case,
    /// The `-key` both sides are given.
    pub key: String,
}

impl Pair {
    /// kcptun's defaults on both sides with [`DEFAULT_KEY`].
    pub fn defaults() -> Self {
        Pair {
            client: Case::new(),
            server: Case::new(),
            key: DEFAULT_KEY.to_string(),
        }
    }

    /// Applies `f` to both sides.
    fn both(&mut self, f: impl Fn(&mut Case)) {
        f(&mut self.client);
        f(&mut self.server);
    }
}

