/// How long one case may take before it is called a failure.
pub const CASE_TIMEOUT: Duration = Duration::from_secs(240);

/// Log substrings that mean something went wrong. None of them occurs in a healthy run of either
/// implementation, whose output is startup lines plus `stream opened` / `stream closed`.
// Go: kcptun@v0.0.0-20260208051026-39935d5307f0 client/main.go, server/main.go (log sites)
const ERROR_MARKERS: &[&str] = &[
    "panicked at",
    "fatal runtime error",
    "pipe:",
    "re-connecting:",
    "SetDSCP:",
    "SetReadBuffer:",
    "SetWriteBuffer:",
    "Warning",
    "WARNING",
    "scavenger:",
];

/// The lines of `log` that match [`ERROR_MARKERS`].
pub fn error_lines(log: &str) -> Vec<&str> {
    log.lines()
        .filter(|l| ERROR_MARKERS.iter().any(|m| l.contains(m)))
        .collect()
}

/// The result of one (case, pairing) run.
#[derive(Clone, Debug)]
pub struct RunReport {
    /// [`InteropCase::id`].
    pub case_id: String,
    /// Which pairing ran.
    pub pairing: Pairing,
    /// What the half-close workload was allowed to do.
    pub expectation: Expectation,
    /// How many response bytes the half-close probe received.
    pub half_close_bytes: u64,
    /// How many it asked for ([`Workload::response_bytes`]).
    pub response_bytes: u64,
    /// How long the whole run took.
    pub elapsed: Duration,
    /// Anything worth recording that is not a failure (e.g. an observed V04 truncation).
    pub notes: Vec<String>,
}

impl RunReport {
    /// The table cell: `ok` for a strict run, or `ok (V11 253952/262144)` for one where a Go
    /// client was allowed to truncate: the numbers say how much of the half-close answer
    /// survived, so `262144/262144` means the expected truncation did not happen on this run.
    pub fn status(&self) -> String {
        match self.expectation {
            Expectation::Complete => "ok".to_string(),
            e => format!(
                "ok ({} {}/{})",
                e.tag(),
                self.half_close_bytes,
                self.response_bytes
            ),
        }
    }

    /// [`status`](Self::status) plus anything else worth seeing on the console.
    pub fn detail(&self) -> String {
        if self.notes.is_empty() {
            self.status()
        } else {
            format!("{} [{}]", self.status(), self.notes.join("; "))
        }
    }
}

/// Runs one (case, pairing): brings the tunnel up, drives all three workloads, checks both logs
/// and tears everything down.
///
/// The error string always starts with [`InteropCase::describe`], so a failing case in a
/// 100-plus-run matrix can be reproduced from the test output alone.
pub async fn run_case(
    case: &InteropCase,
    pairing: Pairing,
    workload: &Workload,
) -> Result<RunReport, String> {
    let started = Instant::now();
    match tokio::time::timeout(CASE_TIMEOUT, run_case_inner(case, pairing, workload)).await {
        Ok(Ok(mut report)) => {
            report.elapsed = started.elapsed();
            Ok(report)
        }
        Ok(Err(e)) => Err(format!(
            "{}\n  pairing: {pairing}\n  FAILED after {:?}: {e}",
            case.describe(),
            started.elapsed()
        )),
        Err(_) => Err(format!(
            "{}\n  pairing: {pairing}\n  TIMED OUT after {CASE_TIMEOUT:?}",
            case.describe()
        )),
    }
}

/// [`run_case`] without the timeout and the configuration dump.
async fn run_case_inner(
    case: &InteropCase,
    pairing: Pairing,
    workload: &Workload,
) -> Result<RunReport, String> {
    let expectation = Expectation::of(case, pairing);
    let target = MatrixTarget::start()
        .await
        .map_err(|e| format!("starting the target server: {e}"))?;

    let mut tunnel = Tunnel::builder(target.target())
        .client_case(case.client.clone())
        .server_case(case.server.clone())
        .client_impl(pairing.client)
        .server_impl(pairing.server)
        .key(case.key.clone())
        // Every stream of this matrix is torn down by the application, and `-closewait` delays
        // exactly that teardown by its full number of seconds per direction. The default of 30 s
        // would add minutes per case and pins nothing this matrix is about: 09.3's
        // `e2e_closewait_delays_the_half_close_of_the_target` owns that behaviour.
        .server_args(["-closewait", "0"])
        .start()
        .await
        .map_err(|e: StartError| format!("starting the tunnel: {e}"))?;

    let result = drive(&mut tunnel, workload, expectation).await;
    let (half_close_bytes, mut notes) = match result {
        Ok(v) => v,
        Err(e) => {
            // The logs say far more than the I/O error on its own does.
            return Err(format!("{e}\n{}", logs_of(&tunnel)));
        }
    };

    if expectation == Expectation::GoSmuxTruncation && half_close_bytes == 0 {
        // V11 cuts what is still unread in smux's buffer, so it does not normally take the whole
        // answer: a zero here looks like V04's total loss without `-QPP` to explain it. It is
        // still a correct (empty) prefix, so it is not a failure, but it is worth a look.
        notes.push(
            "the half-close probe returned 0 bytes on a V11 row; V11 normally cuts only part of \
             the answer, so compare this crossing with its go->go control"
                .to_string(),
        );
    }

    tunnel.check_alive()?;
    if target.bad_headers() != 0 {
        return Err(format!(
            "{} target connections did not start with a readable header",
            target.bad_headers()
        ));
    }
    check_target_connections(&target, workload, half_close_bytes, expectation).await?;
    check_logs(&tunnel, expectation, &mut notes)?;
    target.shutdown().await;

    Ok(RunReport {
        case_id: case.id.clone(),
        pairing,
        expectation,
        half_close_bytes,
        response_bytes: workload.response_bytes,
        elapsed: Duration::ZERO,
        notes,
    })
}

/// Runs the three workloads over an already-started tunnel. Returns the half-close response
/// length and any notes.
async fn drive(
    tunnel: &mut Tunnel,
    workload: &Workload,
    expectation: Expectation,
) -> Result<(u64, Vec<String>), String> {
    // 1. Bulk, one stream, `bulk_bytes` each way.
    let mut app = tunnel
        .connect()
        .await
        .map_err(|e| format!("bulk: connecting to the client: {e}"))?;
    echo_exchange(&mut app, 0xB0_1C, workload.bulk_bytes)
        .await
        .map_err(|e| format!("bulk: {e}"))?;
    drop(app);

    // 2. `streams` concurrent short streams.
    let mut tasks = Vec::with_capacity(workload.streams);
    for i in 0..workload.streams {
        let endpoint = tunnel.local().clone();
        let len = workload.stream_bytes;
        let seed = 0x51EA_u64.wrapping_add(i as u64);
        tasks.push(tokio::spawn(async move {
            let mut app = crate::e2e::connect_local(&endpoint)
                .await
                .map_err(|e| format!("stream {i}: connecting to the client: {e}"))?;
            echo_exchange(&mut app, seed, len)
                .await
                .map_err(|e| format!("stream {i}: {e}"))
        }));
    }
    let mut first_error: Option<String> = None;
    for task in tasks {
        let failure = match task.await {
            Ok(Ok(())) => continue,
            Ok(Err(e)) => e,
            Err(e) => format!("stream task: {e}"),
        };
        // Every task is awaited even after the first failure, so no stream is left running.
        first_error.get_or_insert(failure);
    }
    if let Some(e) = first_error {
        return Err(e);
    }

    // 3. The half-close probe.
    let seed = 0xA1F0_u64;
    let expected = PrngStream::to_vec(seed, workload.response_bytes as usize);
    let mut app = tunnel
        .connect()
        .await
        .map_err(|e| format!("half-close: connecting to the client: {e}"))?;
    let got = half_close_probe(
        &mut app,
        seed,
        workload.response_bytes,
        workload.request_bytes,
        workload.half_close_read_delay,
        &expected,
    )
    .await?;
    drop(app);

    // A short answer is a failure unless the expectation names the Go behaviour that shortens
    // it; when it does, the report's byte count says how much survived.
    if got != workload.response_bytes && !expectation.allows_truncation() {
        return Err(format!(
            "half-close probe: {got} of {} response bytes arrived; a complete response is \
             required here",
            workload.response_bytes
        ));
    }
    Ok((got, Vec::new()))
}

/// The workload is only worth what it actually pushed through, so the target's own count has to
/// agree: one bulk stream, [`Workload::streams`] concurrent ones, and the half-close probe.
///
/// The probe's connection is the one exception. When `-QPP` makes a Go client close the stream
/// outright (V04) the application sees EOF as soon as the *client* gives up, which can be before
/// the server has finished dialling the target, and since no response byte arrives there is
/// nothing to wait for. Such a run therefore requires only that the dial has not produced a
/// *spurious* extra connection. Every other run must show all of them, after a short grace period
/// for the server's dial.
async fn check_target_connections(
    target: &MatrixTarget,
    workload: &Workload,
    half_close_bytes: u64,
    expectation: Expectation,
) -> Result<(), String> {
    let all = workload.streams as u64 + 2;
    let probe_certain = half_close_bytes > 0 || !expectation.allows_truncation();
    let required = if probe_certain { all } else { all - 1 };
    let deadline = Instant::now() + Duration::from_secs(5);
    while target.connections() < required && Instant::now() < deadline {
        tokio::time::sleep(Duration::from_millis(20)).await;
    }
    let seen = target.connections();
    if seen < required {
        return Err(format!(
            "the target saw {seen} connections, expected at least {required} (1 bulk + {} \
             concurrent + {} half-close)",
            workload.streams,
            u8::from(probe_certain)
        ));
    }
    if seen > all {
        return Err(format!(
            "the target saw {seen} connections, more than the {all} the workload opens"
        ));
    }
    Ok(())
}

/// Both processes' logs, labelled, for a failure message.
fn logs_of(tunnel: &Tunnel) -> String {
    format!(
        "--- client ({}) ---\n{}--- server ({}) ---\n{}",
        tunnel.client_impl(),
        tunnel.client_log(),
        tunnel.server_impl(),
        tunnel.server_log()
    )
}

/// Fails on any log line matching the [`ERROR_MARKERS`] denylist.
///
/// This is a denylist, not an allowlist: a line neither implementation prints in a healthy run
/// fails the case, but a log site that reports its error bare (Go's `server/main.go` does so for
/// `smux.Server`, `mux.AcceptStream` and the target dial) would pass unnoticed. Those failures
/// are caught by the workload instead, no byte of the response would arrive.
fn check_logs(
    tunnel: &Tunnel,
    expectation: Expectation,
    notes: &mut Vec<String>,
) -> Result<(), String> {
    for (what, log) in [
        ("client", tunnel.client_log()),
        ("server", tunnel.server_log()),
    ] {
        let panics = panic_lines(&log);
        if !panics.is_empty() {
            return Err(format!("{what} panicked:\n{}", panics.join("\n")));
        }
        let bad: Vec<&str> = error_lines(&log)
            .into_iter()
            // A Go client tears its own half-closed stream down (V11, and V04 as well with
            // `-QPP`), so the reverse copy of its own `Pipe` ends with an error rather than EOF
            // and kcptun logs it. That `pipe:` line *is* the expected behaviour, not a second
            // fault. Everything else still fails, on both sides.
            .filter(|l| !(expectation.allows_truncation() && l.contains("pipe:")))
            .collect();
        if !bad.is_empty() {
            return Err(format!(
                "{what} logged {} unexpected line(s):\n{}",
                bad.len(),
                bad.join("\n")
            ));
        }
        if expectation.allows_truncation() && log.lines().any(|l| l.contains("pipe:")) {
            notes.push(format!("{what} logged `pipe:` for the torn-down stream"));
        }
    }
    Ok(())
}

