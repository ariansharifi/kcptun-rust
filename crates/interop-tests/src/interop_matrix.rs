/// Every case of the matrix: [`crypt_cases`], then [`pairwise_cases`], then [`production_case`].
pub fn all_cases() -> Vec<InteropCase> {
    let mut v = crypt_cases();
    v.extend(pairwise_cases());
    v.push(production_case());
    v
}

/// The cases whose id contains `filter` (the whole list when it is empty).
pub fn select(cases: Vec<InteropCase>, filter: &str) -> Vec<InteropCase> {
    if filter.is_empty() {
        return cases;
    }
    cases
        .into_iter()
        .filter(|c| c.id.contains(filter))
        .collect()
}

