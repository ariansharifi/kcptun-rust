/// The four binaries a full matrix run uses.
const REPORTED_BINARIES: [(Impl, &str); 4] = [
    (Impl::Go, "client"),
    (Impl::Go, "server"),
    (Impl::Rust, "client"),
    (Impl::Rust, "server"),
];

/// `date -u`, or an empty string if `date` is not there. Committed reports say when they ran, and
/// no crate in this workspace carries a clock library.
fn utc_now() -> String {
    std::process::Command::new("date")
        .args(["-u", "+%Y-%m-%d %H:%M:%SZ"])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .unwrap_or_default()
}

/// The first 16 hex digits of a file's SHA-256, so a report names the exact binaries that ran.
fn file_digest(path: &std::path::Path) -> String {
    match std::fs::read(path) {
        Ok(bytes) => {
            let mut h = Sha256::new();
            h.update(&bytes);
            hex::encode(h.finalize())[..16].to_string()
        }
        Err(e) => format!("unreadable: {e}"),
    }
}

/// What `<bin> -v` prints, on one line.
fn binary_version(path: &std::path::Path) -> String {
    std::process::Command::new(path)
        .arg("-v")
        .output()
        .ok()
        .map(|o| {
            let mut s = String::from_utf8_lossy(&o.stdout).trim().to_string();
            if s.is_empty() {
                s = String::from_utf8_lossy(&o.stderr).trim().to_string();
            }
            s
        })
        .unwrap_or_else(|| "unknown".to_string())
}

/// `path` relative to the workspace root when it is inside it, so a committed report does not
/// carry the home directory of whoever ran it.
fn short_path(path: &std::path::Path) -> String {
    path.strip_prefix(crate::bins::workspace_root())
        .unwrap_or(path)
        .display()
        .to_string()
}

/// A Markdown table naming the host and the four binaries that ran, with their digests.
pub fn environment_table() -> String {
    let mut s = String::new();
    s.push_str("| Binary | Path | `-v` | SHA-256 (first 8 bytes) |\n|---|---|---|---|\n");
    for (which, name) in REPORTED_BINARIES {
        let row = match crate::bins::bin(which, name) {
            Ok(path) => format!(
                "| {which} {name} | `{}` | {} | `{}` |\n",
                short_path(&path),
                binary_version(&path),
                file_digest(&path)
            ),
            Err(e) => format!(
                "| {which} {name} | not found | - | - |\n<!-- {} -->\n",
                e.to_string().replace('\n', " ")
            ),
        };
        s.push_str(&row);
    }
    s
}

/// Opens a platform's section in `docs/interop-matrix.md`; see [`merge`].
pub const PLATFORM_MARKER: &str = "<!-- platform: ";

/// This machine's key in that document, e.g. `macos/aarch64`.
pub fn platform_key() -> String {
    format!("{}/{}", std::env::consts::OS, std::env::consts::ARCH)
}

/// The part of the document that comes from the code alone: the title, how the file is produced,
/// what the cells mean, and the case list.
///
/// It is rewritten from scratch on every run, so the committed file can never drift from
/// [`all_cases`].
pub fn preamble() -> String {
    let mut s = String::new();
    s.push_str("# Go ↔ Rust interop matrix\n\n");
    s.push_str(
        "Plan step 09.4. Every case below runs the real `kcptun-client` and `kcptun-server` \
         binaries on loopback in **all four pairings**: `go->rs` and `rs->go` are the interop \
         crossings, `go->go` and `rs->rs` are **controls**. A control that fails means the \
         harness is wrong, not the port: `go->go` runs no Rust at all.\n\n",
    );
    s.push_str(
        "Regenerate one platform's section (the others are kept):\n\n```sh\ncargo build \
         --release -p kcptun-client -p kcptun-server\ntools/fetch-reference.sh --skip-latest \
         --skip-tests\nKCPTUN_INTEROP_MATRIX_OUT=docs/interop-matrix.md \\\n  cargo test -p \
         kcptun-interop-tests --test interop_matrix -- --ignored --nocapture \
         interop_matrix_full\n```\n\n",
    );
    s.push_str(
        "`ok` means every byte of every workload arrived and neither process logged anything \
         unexpected. `ok (V11 a/b)` and `ok (V04+V11 a/b)` mean the same, except that the \
         half-close probe was allowed to come back short and `a` of its `b` bytes did.\n\n",
    );
    s.push_str(
        "Those two tags are the **only** tolerated difference, they apply only to the half-close \
         probe, and only with a **Go client**:\n\n\
         * **V11**: Go's smux discards received-but-unread data when the peer's FIN completes a \
         half-close (`tryHalfCloseCleanup` → `streamClosed` → `recycleTokens`), so the answer is \
         cut, usually at a frame boundary.\n\
         * **V04**, with `-QPP` on top, Go's `std.QPPPort` implements no `CloseWrite`, so \
         kcptun's `Pipe` falls back to `Close()` and tears the whole stream down; nothing of the \
         answer survives, hence the `0/…` rows.\n\n\
         Both reproduce in the `go->go` control. Every byte that *does* arrive is still checked \
         against the expected stream, so a truncation can never hide corruption, and a **Rust \
         client is held to a complete response against either server**: that is what V11 and \
         V04 bought. `b/b` on a V11 row means the expected truncation happened not to occur that \
         run: it is a race inside Go, not a difference between the peers. A V11 row is only ever \
         a statement that what arrived was a correct prefix: `0/b` would be accepted too, so a \
         run that produces one carries a note saying to compare it with its `go->go` control.\n\n",
    );
    s.push_str("## Cases\n\n");
    s.push_str(&case_table());
    s.push_str(
        "\nOne case can be re-run on its own, in all four pairings, with \
         `KCPTUN_INTEROP_MATRIX_FILTER=<case id>`.\n\n",
    );
    s
}

/// One platform's section of the document, opened by its [`PLATFORM_MARKER`].
pub fn section(results: &[CaseResult], workload: &Workload) -> String {
    let passed = results.iter().filter(|r| r.passed()).count();
    let key = platform_key();
    let mut s = format!("{PLATFORM_MARKER}{key} -->\n");
    s.push_str(&format!("## {key}: {}\n\n", utc_now()));
    s.push_str(&format!(
        "**{passed}/{total}** runs passed.\n\n",
        total = results.len()
    ));
    s.push_str(&format!(
        "Workload per run: {bulk} each way on one bulk stream, {streams} concurrent streams of \
         {sb} each way, and a half-close probe that asks for {rb} after `shutdown(SHUT_WR)` \
         (having waited {delay:?} first, so the answer and the peer's FIN are both buffered): \
         all SHA-256 verified, with both processes' logs scanned afterwards. The harness adds \
         `-closewait 0` to the server so teardown is not delayed by 30 s per direction; nothing \
         else is added to a case's flags.\n\n",
        bulk = bytes_human(workload.bulk_bytes),
        streams = workload.streams,
        sb = bytes_human(workload.stream_bytes),
        rb = bytes_human(workload.response_bytes),
        delay = workload.half_close_read_delay,
    ));

    s.push_str("### Binaries\n\n");
    s.push_str(&environment_table());

    s.push_str("\n### Results\n\n");
    s.push_str(&result_table(results));

    s.push_str("\n### Time per pairing\n\n");
    s.push_str(&timing_table(results));

    let failures: Vec<&CaseResult> = results.iter().filter(|r| !r.passed()).collect();
    if failures.is_empty() {
        s.push_str("\nNo failures.\n\n");
    } else {
        s.push_str(&format!("\n### Failures ({})\n\n", failures.len()));
        for f in failures {
            if let Err(e) = &f.outcome {
                s.push_str(&format!("```text\n{e}\n```\n\n"));
            }
        }
    }
    s
}

/// The platform key a section opens with, if it has one.
fn section_key(section: &str) -> Option<String> {
    section
        .strip_prefix(PLATFORM_MARKER)
        .and_then(|rest| rest.split_once(" -->"))
        .map(|(key, _)| key.trim().to_string())
}

/// Splits a document into its platform sections, dropping everything before the first one.
fn split_sections(doc: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for (i, _) in doc.match_indices(PLATFORM_MARKER) {
        // Only a marker that starts its own line opens a section.
        if i != 0 && !doc[..i].ends_with('\n') {
            continue;
        }
        if let Some(last) = out.last_mut() {
            let start = doc.len() - last.len();
            *last = doc[start..i].to_string();
        }
        out.push(doc[i..].to_string());
    }
    out
}

/// The whole `docs/interop-matrix.md`: a freshly generated [`preamble`], then one section per
/// platform, with **this** platform's replaced by `section` and the others kept verbatim.
///
/// That is what lets one committed file carry both the laptop run and the lab-arm64 run while
/// staying a generated artefact: re-running the matrix on macOS rewrites the macOS section and
/// leaves the Linux one alone, and vice versa.
pub fn merge(existing: Option<&str>, section: &str) -> String {
    let key = section_key(section).unwrap_or_else(platform_key);
    let mut sections: Vec<(String, String)> = existing
        .map(split_sections)
        .unwrap_or_default()
        .into_iter()
        .filter_map(|c| section_key(&c).map(|k| (k, c)))
        .collect();
    match sections.iter_mut().find(|(k, _)| *k == key) {
        Some(slot) => slot.1 = section.to_string(),
        None => sections.push((key, section.to_string())),
    }
    let mut s = preamble();
    for (_, text) in sections {
        s.push_str(text.trim_end());
        s.push_str("\n\n");
    }
    s
}

/// [`merge`] of this run's [`section`] into `existing`.
pub fn report(existing: Option<&str>, results: &[CaseResult], workload: &Workload) -> String {
    merge(existing, &section(results, workload))
}

