    #[test]
    fn the_result_table_has_one_column_per_pairing() {
        let results: Vec<CaseResult> = PAIRINGS
            .iter()
            .map(|&pairing| CaseResult {
                case_id: "crypt/aes".to_string(),
                pairing,
                outcome: Ok(RunReport {
                    case_id: "crypt/aes".to_string(),
                    pairing,
                    expectation: Expectation::Complete,
                    half_close_bytes: 1024,
                    response_bytes: 1024,
                    elapsed: Duration::from_secs(1),
                    notes: Vec::new(),
                }),
            })
            .collect();
        let t = result_table(&results);
        assert!(t.starts_with("| Case | go->rs | rs->go | go->go | rs->rs |\n"));
        assert!(t.contains("| `crypt/aes` | ok | ok | ok | ok |"), "{t}");
        // A missing run is a failure, not a blank.
        let t = result_table(&results[..2]);
        assert!(
            t.contains("| `crypt/aes` | ok | ok | **FAIL** (not run) | **FAIL** (not run) |"),
            "{t}"
        );
        // A failed run is loud.
        let mut failed = results.clone();
        failed[0].outcome = Err("boom".to_string());
        assert!(result_table(&failed).contains("| **FAIL** |"));
        assert!(!failed[0].passed() && failed[1].passed());

        // A truncating run says how much of the answer survived, right in the cell.
        let mut truncated = results[0].clone();
        if let Ok(r) = &mut truncated.outcome {
            r.expectation = Expectation::GoSmuxTruncation;
            r.half_close_bytes = 512;
            r.notes.push("client logged `pipe:`".to_string());
        }
        let report = truncated.outcome.as_ref().expect("ok");
        assert_eq!(report.status(), "ok (V11 512/1024)");
        assert_eq!(report.detail(), "ok (V11 512/1024) [client logged `pipe:`]");
        assert_eq!(truncated.cell(), "ok (V11 512/1024)");
    }

