/// `20 MB`, `256 KiB`, `1024 B`, whichever reads best for `n`.
fn bytes_human(n: u64) -> String {
    if n >= 1_000_000 && n.is_multiple_of(1_000_000) {
        format!("{} MB", n / 1_000_000)
    } else if n >= 1024 && n.is_multiple_of(1024) {
        format!("{} KiB", n / 1024)
    } else {
        format!("{n} B")
    }
}

/// Wall time per pairing, with each one's slowest case.
///
/// The interesting column is the total: `rs->rs` against `go->go` is the cheapest honest
/// comparison this matrix offers, since both run the same cases over the same loopback.
pub fn timing_table(results: &[CaseResult]) -> String {
    let mut s = String::new();
    s.push_str("| Pairing | Runs | Total | Slowest case |\n|---|---|---|---|\n");
    for p in PAIRINGS {
        let runs: Vec<&RunReport> = results
            .iter()
            .filter(|r| r.pairing == p)
            .filter_map(|r| r.outcome.as_ref().ok())
            .collect();
        let total: Duration = runs.iter().map(|r| r.elapsed).sum();
        let slowest = match runs.iter().max_by_key(|r| r.elapsed) {
            Some(r) => format!("`{}` at {:.1} s", r.case_id, r.elapsed.as_secs_f64()),
            None => "-".to_string(),
        };
        s.push_str(&format!(
            "| {p} | {} | {:.0} s | {slowest} |\n",
            runs.len(),
            total.as_secs_f64()
        ));
    }
    s
}

/// The Markdown case list `docs/interop-matrix.md` is regenerated from.
pub fn case_table() -> String {
    let mut s = String::new();
    s.push_str("| Case | Group | Configuration |\n|---|---|---|\n");
    for c in all_cases() {
        s.push_str(&format!(
            "| `{}` | {} | {} |\n",
            c.id,
            c.group,
            c.summary.replace('|', "\\|")
        ));
    }
    s
}

/// One row of the report: the outcome of one (case, pairing), failure included.
#[derive(Clone, Debug)]
pub struct CaseResult {
    /// [`InteropCase::id`].
    pub case_id: String,
    /// Which pairing ran.
    pub pairing: Pairing,
    /// The run, or why it failed (the message starts with the full configuration).
    pub outcome: Result<RunReport, String>,
}

impl CaseResult {
    /// True when the run passed.
    pub fn passed(&self) -> bool {
        self.outcome.is_ok()
    }

    /// The cell this result contributes to [`result_table`].
    pub fn cell(&self) -> String {
        match &self.outcome {
            Ok(r) => r.status(),
            Err(_) => "**FAIL**".to_string(),
        }
    }
}

/// The Markdown results table: one row per case, one column per pairing. A (case, pairing) with
/// no result at all is a failure, not a blank: a run that never happened proves nothing.
pub fn result_table(results: &[CaseResult]) -> String {
    let mut s = String::new();
    s.push_str("| Case |");
    for p in PAIRINGS {
        s.push_str(&format!(" {p} |"));
    }
    s.push_str("\n|---|");
    for _ in PAIRINGS {
        s.push_str("---|");
    }
    s.push('\n');

    let mut ids: Vec<&str> = Vec::new();
    for r in results {
        if !ids.contains(&r.case_id.as_str()) {
            ids.push(&r.case_id);
        }
    }
    for id in ids {
        s.push_str(&format!("| `{id}` |"));
        for p in PAIRINGS {
            let cell = results
                .iter()
                .find(|r| r.case_id == id && r.pairing == p)
                .map(CaseResult::cell)
                .unwrap_or_else(|| "**FAIL** (not run)".to_string());
            s.push_str(&format!(" {cell} |"));
        }
        s.push('\n');
    }
    s
}

