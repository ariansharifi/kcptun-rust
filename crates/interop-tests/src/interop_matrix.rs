/// Which implementation runs each end of the tunnel.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct Pairing {
    /// The implementation that runs `kcptun-client`.
    pub client: Impl,
    /// The implementation that runs `kcptun-server`.
    pub server: Impl,
}

impl Pairing {
    /// `go->rs`, `rs->go`, `go->go` or `rs->rs`.
    pub fn label(self) -> String {
        format!("{}->{}", self.client.tag(), self.server.tag())
    }

    /// True for `go->go` and `rs->rs`: both ends are the same implementation, so a failure
    /// indicts the harness rather than the port (see the [module docs](self)).
    pub fn is_control(self) -> bool {
        self.client == self.server
    }
}

impl fmt::Display for Pairing {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.label())
    }
}

